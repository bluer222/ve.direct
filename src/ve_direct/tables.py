def pid_name(pid: int) -> str:
    return PID_MAP.get(pid, f"Unknown (0x{pid:04X})")


def decode_ar(value: int) -> list[str]:
    """Decode AR/WARN bitmask sum into active alarm names."""
    return [name for bit, name in sorted(AR_MAP.items()) if value & bit]


def decode_or(value: int) -> list[str]:
    """Decode OR bitmask into active off-reasons."""
    out = [name for bit, name in sorted(OR_MAP.items()) if value & bit]
    if out:
        unknown = value & ~sum(OR_MAP)
        if unknown:
            out.append(f"Unknown bits 0x{unknown:08X}")
        return out
    return ["No off reason"] if value == 0 else [f"Unknown bits 0x{value:08X}"]


def decode_cap_ble(value: int) -> list[str]:
    """Decode CAP_BLE bitmask into capabilities."""
    out = [name for bit, name in sorted(CAP_BLE_MAP.items()) if value & bit]
    if out:
        unknown = value & ~sum(CAP_BLE_MAP)
        if unknown:
            out.append(f"Unknown bits 0x{unknown:08X}")
        return out
    return ["No BLE off capability"] if value == 0 else [f"Unknown bits 0x{value:08X}"]
