#!/usr/bin/env python3
"""Generate importable label/name -> description dictionaries.

Run from a checkout:
    python tools/generate_descriptions.py
    python tools/generate_descriptions.py -o /path/to/project/vedirect_descriptions.py
    python tools/generate_descriptions.py --check

The output contains literal dictionaries and needs no ve_direct installation.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from ve_direct.registers import (
    EXPERIMENTAL_MULTI_RS_REGISTERS, _FLAVOR_EXPAND, for_flavor,
)
from ve_direct.tables import LABEL_INFO

DEFAULT_OUTPUT = REPO_ROOT / "src" / "ve_direct" / "descriptions.py"

# Keep technical acronyms and expand shortened words in the symbolic names.
WORDS = {
    "AC": "AC", "DC": "DC", "ID": "ID", "BLE": "Bluetooth Low Energy",
    "BMV": "BMV", "MPPT": "MPPT", "RS": "RS", "ORION": "Orion",
    "INV": "Inverter", "BAT": "battery", "CHR": "charger",
    "APP": "application", "VER": "version", "SW": "software",
    "OUT": "output", "IN": "input", "AUX": "auxiliary",
    "MIN": "minimum", "MAX": "maximum", "NOM": "nominal",
    "TEMP": "temperature", "CONFIG": "configuration", "DYN": "dynamic",
    "AH": "amp hours", "SOC": "state of charge", "TTG": "time to go",
    "BMS": "battery management system", "NVM": "nonvolatile memory",
    "TX": "transmit", "RX": "receive", "AES": "AES", "ECO": "eco",
    "MA": "milliamps", "SYNC": "synchronization", "SYNCS": "synchronizations",
    "CHANNEL1": "channel 1", "BATTERYSAFE": "BatterySafe",
}

OVERRIDES = {
    "INV_WAVE_SET50HZ_NOT60HZ": "Inverter AC output frequency selection, 50 Hz or 60 Hz",
    "INV_LOOP_GET_IINV": "Inverter current",
    "BMV_TTG_DELTA_T": "BMV time-to-go averaging period",
    "U_AC_OUT_CURRENT_MA": "Multi RS AC output current, milliamps precision",
}


def hex_description(name: str) -> str:
    if name in OVERRIDES:
        description = OVERRIDES[name]
    elif name.startswith("UNKNOWN_"):
        description = f"Unknown register 0x{name.removeprefix('UNKNOWN_')}"
    else:
        # U_* are observational Multi RS names, not a unit prefix.
        words = name.split("_")
        if words[0] == "U":
            words[0] = "Multi RS"
        description = " ".join(WORDS.get(word, word.lower()) for word in words)
        description = description[0].upper() + description[1:]
    if name in EXPERIMENTAL_MULTI_RS_REGISTERS:
        description += " (experimental Multi RS register)"
    return description


def build_descriptions() -> tuple[dict[str, str], dict[str, dict[str, str]]]:
    stream = {label: info["desc"] for label, info in sorted(LABEL_INFO.items())}
    hexes = {
        flavor: {name: hex_description(name) for name in sorted(for_flavor(flavor))}
        for flavor in sorted(_FLAVOR_EXPAND)
    }
    return stream, hexes


def render_module() -> str:
    stream, hexes = build_descriptions()
    parts = [
        '"""VE.Direct descriptions. Generated by tools/generate_descriptions.py.\n\n'
        'STREAM_DESCRIPTIONS covers known Text labels across all device families.\n'
        'HEX_DESCRIPTIONS maps flavor -> register name -> description. Each flavor\n'
        'includes shared and inherited registers, aliases, and history/timer ranges\n'
        'from for_flavor(). ANY contains the common registers. Overlaps are retained.\n'
        'HEX labels expand register names;\n'
        'unknown and experimental registers are marked explicitly.\n'
        'This module has no runtime dependencies.\n'
        '"""\n',
        '\n__all__ = ["STREAM_DESCRIPTIONS", "HEX_DESCRIPTIONS"]\n',
    ]
    parts.append("\nSTREAM_DESCRIPTIONS = {\n")
    parts.extend(f"    {key!r}: {value!r},\n" for key, value in stream.items())
    parts.append("}\n\nHEX_DESCRIPTIONS = {\n")
    for flavor, mapping in hexes.items():
        parts.append(f"    {flavor!r}: {{\n")
        parts.extend(f"        {key!r}: {value!r},\n" for key, value in mapping.items())
        parts.append("    },\n")
    parts.append("}\n")
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-o", "--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true",
                        help="Check that the output matches current definitions without writing.")
    args = parser.parse_args(argv)
    content = render_module()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != content:
            print(f"Descriptions need regeneration: {args.output}", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(content, encoding="utf-8")
    stream, hexes = build_descriptions()
    count = sum(len(mapping) for mapping in hexes.values())
    print(f"Wrote {len(stream)} stream labels and {count} HEX entries "
          f"across {len(hexes)} flavors to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
